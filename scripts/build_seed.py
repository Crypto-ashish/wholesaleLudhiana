def slugify(s):
    s = s.lower().replace("&", " and ").replace("'", "")
    return re.sub(r"[^a-z0-9]+", "-", s).strip("-")

def q(v):
    if v is None: return "null"
    if isinstance(v, bool): return "true" if v else "false"
    if isinstance(v, (int, float)): return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def j(v): return q(json.dumps(v, ensure_ascii=False))
def paise(v): return None if v in (None, 0) else int(round(v * 100))

out = ["-- Starter catalogue for Wholesale Ludhiana. Generated by scripts/build_seed.py from the owner's spreadsheets."]
seen, sub_slug = set(), {}
for i, (name, slug, desc, subs) in enumerate(CATS):
    seen.add(slug)
    out.append(f"INSERT INTO categories (slug, name, description, sort, seo_title, seo_description) VALUES ({q(slug)}, {q(name)}, {q(desc)}, {i}, {q(name + ' Wholesale in Ludhiana | Wholesale Ludhiana')}, {q(desc)});")
for i, (name, slug, desc, subs) in enumerate(CATS):
    for k, s in enumerate(subs):
        ss = slugify(s)
        if ss in seen: ss = f"{ss}-{slug.split('-')[0]}"
        seen.add(ss); sub_slug[(slug, s)] = ss
        out.append(f"INSERT INTO categories (slug, parent, name, sort) VALUES ({q(ss)}, {q(slug)}, {q(s)}, {k});")

pslugs = set()
def product(name, cat, sub, **kw):
    base = slugify(name)[:70] or "product"; s = base; n = 2
    while s in pslugs: s = f"{base}-{n}"; n += 1
    pslugs.add(s)
    imgs = kw.get("images", [])
    variants = [{"id": slugify(v["name"])[:40] or f"v{i}", "label": v["name"], "price_paise": paise(v.get("price")), "available": v.get("available", True)} for i, v in enumerate(kw.get("variants", []))]
    ids = set()
    for i, v in enumerate(variants):
        while v["id"] in ids: v["id"] += f"-{i}"
        ids.add(v["id"])
    cols = dict(slug=s, name=name, category=cat, subcategory=sub_slug[(cat, sub)], brand=kw.get("brand", ""), sku=kw.get("sku", ""),
                description=kw.get("description", ""), unit=kw.get("unit", "piece"), moq=kw.get("moq", 1),
                price_paise=paise(kw.get("price", 0)), mrp_paise=paise(kw.get("mrp")),
                tiers=json.dumps([{"min": t["min"], "price_paise": paise(t["price"])} for t in kw.get("tiers", [])]),
                gst_rate=kw.get("gst_rate"), track_stock=int(kw.get("track_stock", False)), stock=kw.get("stock", 0),
                image=imgs[0] if imgs else "", gallery=json.dumps(imgs[1:]), specs=json.dumps(kw.get("specs", []), ensure_ascii=False),
                variants=json.dumps(variants, ensure_ascii=False),
                featured=int(kw.get("best", False)), deal=int(kw.get("deal", False)), is_new=int(kw.get("new", False)),
                seasonal=int(kw.get("seasonal", False)), bulk=int(kw.get("bulk", False)), sort=len(pslugs))
    out.append(f"INSERT INTO products ({', '.join(cols)}) VALUES ({', '.join(q(v) for v in cols.values())});")

